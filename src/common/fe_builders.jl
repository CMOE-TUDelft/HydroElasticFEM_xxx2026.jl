"""
Thin builders over the HydroElasticFEM.jl API for the verification tests.
No weak forms are implemented here: every operator comes from HydroElasticFEM.

Configuration A, vertical section (`configA_channel`): the plate covers the
whole free surface of a channel of depth H. Waves are absorbed by sponge
layers on the plate at both ends, where the bending rigidity is made
viscoelastic, EI(x) = C_ρ (1 − i s(x)), with s ramping from 0 to `strength`
over `wavelengths` plate wavelengths; the channel ends are rigid walls.
Waves are generated by a density-normalised force F on the plate, spread as a
uniform pressure F/b over a patch of `source_elements` elements whose ends
are mesh nodes (exact quadrature). HydroElasticFEM's `rhs_fn` takes
distributed loads only, so a true point force is not available; the patch
response G_b(x − x_s) is exact for |x − x_s| ≥ b/2 (`References.green_1d_patch`,
`References.point_source_field_1d` with `b`).

    x = 0 ──── sponge ──── buffer ──── window ──── buffer ──── sponge ──── x = L

Positions passed to the builder (source, resonators) are measured from the
start of the window. HydroElasticFEM uses the same time factor as the paper,
exp(−iωt) (damping enters as −iωC, radiation as ∂ₙϕ = ikϕ).
"""
module FEBuilders

using Gridap
using Parameters
import HydroElasticFEM.Geometry as G
import HydroElasticFEM.Physics as P
import HydroElasticFEM.Simulation as S
import HydroElasticFEM.ParameterHandler as PH
using HydroElasticFEM: map_vertical_GP_for_const_dep

using Roots: find_zero, Bisection
using ..ParameterSets: HostSpec, ResonatorSpec
using ..References: k0

export MeshSpec, SpongeSpec, ConfigALayout, configA_channel, solve_configA, ladder_mesh

"""
Discretisation: `elements_per_wavelength` along the plate (relative to the
plate wavelength λ_p at the run frequency), `ny` vertical elements in a
geometric progression of ratio `vertical_ratio` (finest at the surface),
polynomial `order` for ϕ and η, C/DG penalty `γ`.
"""
@with_kw struct MeshSpec
    elements_per_wavelength::Int = 16
    ny::Int = 10
    vertical_ratio::Float64 = 1.15
    order::Int = 2
    γ::Float64 = 6.0
end

"""
    ladder_mesh(h, ω, level; order=2, base=8)

Level `level` (0, 1, 2, …) of the mesh ladder of the test matrix (§0.3):
`base·2^level` elements per plate wavelength λ_p and `base·2^level` vertical
elements, graded so that the top cell is half the horizontal element size
(k₀h_z ≤ 0.2 from level 1 on); uniform when H/ny is already that fine.
"""
function ladder_mesh(h::HostSpec, ω::Real, level::Integer; order::Int=2, base::Int=8)
    n = base * 2^level
    h_top = 2π / k0(h, ω) / n / 2
    ratio = h.H / n <= h_top ? 1.0 :
            find_zero(r -> h.H * (r - 1) / (r^n - 1) - h_top, (1.0 + 1e-12, 10.0), Bisection())
    return MeshSpec(elements_per_wavelength=n, ny=n, vertical_ratio=ratio, order=order)
end

"""
Plate sponge: length in plate wavelengths, maximum loss factor and ramp power.
Defaults from the P1 bare-plate study at ω = 10 (patch source vs exact G_b,
24 elements/λ_p): 3 λ_p, s = 1 → 19 % error (ramp reflection); 6 λ_p, s = 3
→ 0.95 % with P2 and 0.07 % with P3, converging at order ≈ 2 in x with P2,
insensitive to the wall distance and to vertical refinement.
"""
@with_kw struct SpongeSpec
    wavelengths::Float64 = 6.0
    strength::Float64 = 3.0
    power::Int = 2
end

"Absolute geometry of a configuration-A channel (all in metres)."
struct ConfigALayout
    L::Float64
    H::Float64
    λ_p::Float64
    sponge_length::Float64
    window::Tuple{Float64,Float64}
    source_x::Union{Nothing,Float64}
    source_width::Float64
    resonator_xs::Vector{Float64}
    nx::Int
    element_size::Float64
end

"Field symbols of a HydroElasticFEM `FieldMap`, ordered by field index."
function _field_order(fieldmap)
    m = fieldmap._map
    return [s for (s, _) in sort!(collect(m); by=last)]
end

"Loss factor s(x) of the plate sponges (0 outside the sponges)."
function sponge_loss(x::Real, layout_L::Real, Ls::Real, sp::SpongeSpec)
    ξ = max(Ls - x, x - (layout_L - Ls), 0.0) / Ls
    return sp.strength * ξ^sp.power
end

"""
    configA_channel(h, ω; window_length, resonators=ResonatorSpec[], resonator_xs=Float64[],
                    source_x=nothing, F=1.0, source_elements=2, gap=nothing,
                    mesh=MeshSpec(), sponge=SpongeSpec())

Build the configuration-A vertical-section problem at frequency `ω`.
`resonator_xs` and `source_x` are offsets from the window start; the source
centre is snapped to the nearest mesh node. `snap_resonators` moves each
resonator to the nearest mesh node (`:node`) or element midpoint
(`:midelement`); `:none` keeps the given positions. The geometry and mesh
are sized with the plate wavelength at `design_ω` (default `ω`), so that a
frequency sweep at fixed `design_ω` uses one domain and one mesh. `gap` is the buffer between
sponge and window (default one plate wavelength).
Returns `(problem, layout)`.
"""
function configA_channel(h::HostSpec, ω::Real; window_length::Real,
                         resonators::AbstractVector{ResonatorSpec}=ResonatorSpec[],
                         resonator_xs::AbstractVector{<:Real}=Float64[],
                         source_x::Union{Nothing,Real}=nothing, F::Number=1.0,
                         source_elements::Int=2, snap_resonators::Symbol=:none,
                         design_ω::Real=ω,
                         gap::Union{Nothing,Real}=nothing,
                         mesh::MeshSpec=MeshSpec(), sponge::SpongeSpec=SpongeSpec())
    h.C_ρ > 0 || throw(ArgumentError("configuration-A sponges act on bending: C_ρ must be positive"))
    h.τ == h.τ_b || throw(ArgumentError("HydroElasticFEM uses one Rayleigh τ for tension and bending (τ = τ_b)"))
    length(resonators) == length(resonator_xs) || throw(DimensionMismatch("one position per resonator"))
    isnothing(source_x) && isempty(resonators) && throw(ArgumentError("nothing drives the problem"))

    λ_p = 2π / k0(h, design_ω)
    Ls = sponge.wavelengths * λ_p
    buffer = isnothing(gap) ? λ_p : gap
    x_w = Ls + buffer
    L = 2 * (Ls + buffer) + window_length
    nx = ceil(Int, L * mesh.elements_per_wavelength / λ_p)
    he = L / nx
    xr = collect(Float64, resonator_xs) .+ x_w
    if snap_resonators == :node
        xr = round.(xr ./ he) .* he
    elseif snap_resonators == :midelement
        xr = (floor.(xr ./ he) .+ 0.5) .* he
    elseif snap_resonators != :none
        throw(ArgumentError("snap_resonators must be :none, :node or :midelement"))
    end
    xs_src = isnothing(source_x) ? nothing : round((x_w + source_x) / he) * he
    b = source_elements * he
    layout = ConfigALayout(L, h.H, λ_p, Ls, (x_w, x_w + window_length), xs_src, b, xr, nx, he)

    H, ny, r = h.H, mesh.ny, mesh.vertical_ratio
    vertical_map(x) = VectorValue(x[1], map_vertical_GP_for_const_dep(x[2] - H, r, ny, H; dbgmsg=false))
    res_domains = [G.ResonatorDomain(location=[x, 0.0], delta_symbol=Symbol("δ$i")) for (i, x) in enumerate(xr)]
    tank = G.TankDomain(L=L, H=H, nx=nx, ny=ny, map=vertical_map, is_periodic=(false, false),
                        structure_domains=[G.StructureDomain(L=L, x₀=[0.0, 0.0], domain_symbol=:Γs)],
                        resonator_domains=res_domains)

    fe(; kw...) = PH.FESpaceConfig(; order=mesh.order, vector_type=Vector{ComplexF64}, kw...)
    potential = P.PotentialFlow(g=h.g, ρw=h.ρ, fe=fe(), space_domain_symbol=:Ω)
    EI(x) = h.C_ρ * (1 - im * sponge_loss(x[1], L, Ls, sponge))
    plate = P.TensionedEulerBernoulliBeam(L=L, mᵨ=h.m_ρ, EIᵨ=EI, Tᵨ=h.T_ρ, τ=h.τ, g=h.g,
                                          symbol=:η, fe=fe(γ=mesh.γ), space_domain_symbol=:Γs)
    entities = P.PhysicsParameters[potential, plate]
    if !isempty(resonators)
        N = length(resonators)
        push!(entities, P.resonator_array(N, [r.m_ρ * h.ρ for r in resonators],
                                          [r.k_ρ * h.ρ for r in resonators],
                                          [r.c_ρ * h.ρ for r in resonators];
                                          delta_domain_symbols=[Symbol("δ$i") for i in 1:N], ρw=h.ρ,
                                          host_domain_symbol=:Γs,   # must match the plate's space domain
                                          fe=PH.FESpaceConfig(space_type=VectorValue{1,Float64},
                                                              vector_type=Vector{ComplexF64})))
    end

    rhs_fn = nothing
    if !isnothing(xs_src)
        load(x) = abs(x[1] - xs_src) < b / 2 ? complex(F / b) : zero(ComplexF64)
        # `rhs_fn` returns one load per field, in the field order of the FieldMap
        # it receives (HydroElasticFEM's internal `_map`; no public accessor).
        rhs_fn = (ctx, y) -> [sym == :η ? load : 0.0 for sym in _field_order(y)]
    end
    problem = S.build_problem(tank, entities, PH.FreqDomainConfig(ω=ω); rhs_fn=rhs_fn)
    return problem, layout
end

"""
    solve_configA(h, ω; kwargs...)

Build and solve a configuration-A problem (see `configA_channel`). Returns the
plate deflection `ηh`, the resonator displacements `q` (in resonator order),
the layout and the `SimResult`.
"""
function solve_configA(h::HostSpec, ω::Real; kwargs...)
    problem, layout = configA_channel(h, ω; kwargs...)
    result = S.simulate(problem)
    uh = result.solution
    ηh = uh[result.fmap[:η]]
    nres = length(layout.resonator_xs)
    q = ComplexF64[first(get_free_dof_values(uh[result.fmap[Symbol("q$i")]])) for i in 1:nres]
    return (ηh=ηh, q=q, layout=layout, result=result)
end

end # module FEBuilders
